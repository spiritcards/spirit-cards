export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** Pixel width of a string at a given scale (1px gap between glyphs). */
export function textWidth(text: string, scale: number): number {
  const n = text.length;
  if (n === 0) return 0;
  return (n * GLYPH_W + (n - 1)) * scale;
}

export type TextOpts = {
  /** left x, top y of the text box, in canvas px */
  x: number;
  y: number;
  scale: number;
  color?: string;
  /** "left" (default) | "right" | "center" */
  align?: "left" | "right" | "center";
  /** 1px drop shadow colour for contrast on busy art (null disables) */
  shadow?: string | null;
};

/** Render text as SVG <rect> glyphs (no font dependency). */
export function textSvg(text: string, opts: TextOpts): string {
  const { scale, color = "#eef2ff" } = opts;
  const up = text.toUpperCase();
  const w = textWidth(up, scale);
  let x0 = opts.x;
  if (opts.align === "right") x0 = opts.x - w;
  else if (opts.align === "center") x0 = opts.x - Math.floor(w / 2);
  const y0 = opts.y;
  const shadow = opts.shadow === undefined ? "#0b1020" : opts.shadow;

  const rects = (col: string, dx: number, dy: number) => {
    const out: string[] = [];
    for (let ci = 0; ci < up.length; ci++) {
      const glyph = G[up[ci]] ?? G[" "];
      const cx = x0 + ci * (GLYPH_W + 1) * scale + dx;
      for (let r = 0; r < GLYPH_H; r++) {
        for (let c = 0; c < GLYPH_W; c++) {
          if (glyph[r][c] !== "1") continue;
          out.push(
            `<rect x="${cx + c * scale}" y="${y0 + r * scale + dy}" width="${scale}" height="${scale}" fill="${col}"/>`,
          );
        }
      }
    }
    return out.join("");
  };

  return (shadow ? rects(shadow, scale, scale) : "") + rects(color, 0, 0);
}
